import { GoogleGenAI, Type } from '@google/genai';
import {
  FlavorEntity,
  FusionCandidateIdea,
  FusionRequest,
  NormalizedRecipe,
} from '../../src/types/culinary';

function isGeminiConfigured(): boolean {
  const key = process.env.GEMINI_API_KEY;
  return Boolean(
    key &&
      key.trim().length > 5 &&
      key !== 'MY_GEMINI_API_KEY' &&
      key !== 'YOUR_GEMINI_API_KEY'
  );
}

/**
 * Uses server-side @google/genai (`gemini-3.8-flash`) to generate creative
 * candidate fusion ideas grounded strictly in verified FlavorDB molecules and RecipeDB recipes.
 */
export async function generateAiGroundedFusionIdea(
  request: FusionRequest,
  sourceRecipes: NormalizedRecipe[],
  matchedEntities: FlavorEntity[],
  fallbackIdea: FusionCandidateIdea
): Promise<FusionCandidateIdea | null> {
  if (!isGeminiConfigured()) {
    return null;
  }

  try {
    const ai = new GoogleGenAI({
      apiKey: process.env.GEMINI_API_KEY,
      httpOptions: {
        headers: {
          'User-Agent': 'aistudio-build',
        },
      },
    });

    const entityContext = matchedEntities
      .map(
        (e) =>
          `${e.name} (FlavorDB #${e.entityId}, Category: ${e.category}, Key Molecules: ${e.molecules
            .slice(0, 4)
            .map((m) => m.commonName)
            .join(', ')})`
      )
      .join('; ');

    const recipeContext = sourceRecipes
      .slice(0, 3)
      .map((r) => `${r.title} (${r.cuisine}, ${r.dietaryType})`)
      .join('; ');

    const prompt = `Design 1 creative, culinary-grade fusion recipe concept grounded in computational gastronomy.
Base Ingredient: ${request.baseIngredient}
Additional Ingredients: ${request.additionalIngredients.join(', ')}
Target Cuisine Preference: ${request.targetCuisine || 'Cross-Cultural'}
Dietary Requirement: ${request.dietaryPreference}
Verified FlavorDB Ingredient Profiles: ${entityContext}
Related RecipeDB Source Recipes: ${recipeContext}

Provide a candidate fusion concept that explains the exact molecular flavor bridges between the selected ingredients.`;

    const response = await ai.models.generateContent({
      model: 'gemini-3.8-flash',
      contents: prompt,
      config: {
        systemInstruction:
          'You are a computational gastronomy chef-scientist. Never claim a generated fusion concept is a pre-existing traditional recipe. Ground your explanation in the provided FlavorDB aroma compounds and RecipeDB context. Keep responses concise.',
        responseMimeType: 'application/json',
        responseSchema: {
          type: Type.OBJECT,
          properties: {
            title: { type: Type.STRING },
            subtitle: { type: Type.STRING },
            whyItWorks: { type: Type.STRING },
            proposedIngredients: {
              type: Type.ARRAY,
              items: {
                type: Type.OBJECT,
                properties: {
                  name: { type: Type.STRING },
                  role: { type: Type.STRING },
                  quantityHint: { type: Type.STRING },
                },
                required: ['name', 'role', 'quantityHint'],
              },
            },
            preparationSteps: {
              type: Type.ARRAY,
              items: { type: Type.STRING },
            },
          },
          required: ['title', 'subtitle', 'whyItWorks', 'proposedIngredients', 'preparationSteps'],
        },
      },
    });

    const text = response.text;
    if (!text) return null;
    const parsed = JSON.parse(text.trim());

    return {
      ...fallbackIdea,
      id: `fusion-ai-${Date.now()}`,
      title: parsed.title || fallbackIdea.title,
      subtitle: parsed.subtitle || fallbackIdea.subtitle,
      generationMethod: 'AI-Assisted Synthesis (Grounded in FlavorDB + RecipeDB)',
      isVerifiedExistingRecipe: false,
      whyItWorks: parsed.whyItWorks || fallbackIdea.whyItWorks,
      proposedIngredients:
        Array.isArray(parsed.proposedIngredients) && parsed.proposedIngredients.length > 0
          ? parsed.proposedIngredients
          : fallbackIdea.proposedIngredients,
      preparationSteps:
        Array.isArray(parsed.preparationSteps) && parsed.preparationSteps.length > 0
          ? parsed.preparationSteps
          : fallbackIdea.preparationSteps,
      provenance: {
        source: 'gemini_ai_synthesis',
        sourceLabel: 'Gemini 3.8 Flash Server-Side Synthesis (Grounded in FlavorDB & RecipeDB)',
        isVerifiedApiData: false,
        isDemoFallback: fallbackIdea.provenance.isDemoFallback,
        timestamp: new Date().toISOString(),
        note: 'Creative fusion concept generated by Gemini AI using verified FlavorDB molecular profiles as grounding input.',
      },
    };
  } catch {
    return null;
  }
}

export function getGeminiStatus() {
  return {
    configured: isGeminiConfigured(),
    model: 'gemini-3.8-flash',
  };
}
